'use strict';
module.exports = {
  async status({ homey }) { return homey.app.getPublicStatus(); },
  async diagnostics({ homey }) { return { report: require('./lib/frameo-diagnostics').getReport(homey.app) }; },
  async refresh({ homey, body }) { const device = homey.app.getDevice(body?.id); await device.refreshDetails(); return device.publicStatus(); },
  async sendUrl({ homey, body }) { return homey.app.queueTransfer(homey.app.getDevice(body?.id), 'url', body?.url, body || {}); },
  async requestPermission({ homey, body }) { return homey.app.getDevice(body?.id).requestPermission(body?.access); },
  async galleryFrames({ homey }) { return homey.app.gallery.frames(); },
  async galleryList({ homey, body }) { return homey.app.gallery.list(body || {}); },
  async galleryPreview({ homey, body }) { return homey.app.gallery.preview(body || {}); },
  async galleryDelete({ homey, body }) { return homey.app.gallery.delete(body || {}); },
  async galleryMode({ homey, body }) { return homey.app.gallery.setMode(body || {}); },
  async galleryCheckAccess({ homey, body }) { return homey.app.gallery.checkAccess(body || {}); },
  async galleryVisibility({ homey, body }) { return homey.app.gallery.visibility(body || {}); },
  async groupsList({ homey }) { return homey.app.groups.list(); },
  async groupsSave({ homey, body }) { return homey.app.groups.save(body || {}); },
  async groupsDelete({ homey, body }) { return homey.app.groups.delete(body?.id); },
  async transfersStart({ homey, body }) { return homey.app.transfers.start(body || {}); },
  async transfersManual({ homey, body }) { return homey.app.transfers.enqueueManual(body || {}); },
  async transfersJob({ homey, query }) { return homey.app.transfers.get(query?.jobId); },
  async transfersHistory({ homey }) { return homey.app.transfers.history(); },
  async transfersClear({ homey }) { return homey.app.transfers.clear(); },
  async transfersFinish({ homey, body }) { return homey.app.transfers.finishBatch(body?.batchId); },
  async uploadsStart({ homey, body }) { return homey.app.uploads.start(body || {}); },
  async uploadsChunk({ homey, body }) { return homey.app.uploads.chunk(body || {}); },
  async uploadsFinish({ homey, body }) { return homey.app.uploads.finish(body || {}); },
  async uploadsAbort({ homey, body }) { return homey.app.uploads.abort(body || {}); },
};
